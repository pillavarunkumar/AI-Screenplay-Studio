import type { EvalRun, FeatureScore, SampleScore } from "./scoring";

const DIMENSION_ORDER = ["technique", "emotion", "consistency"] as const;

function formatFeature(feature: FeatureScore): string {
  return DIMENSION_ORDER.map(
    (dimension) =>
      feature.dimensions.find((item) => item.dimension === dimension)?.score ?? 0,
  ).join("/");
}

function escapeCell(value: string): string {
  return value.replace(/\|/g, "\\|").replace(/\n/g, " ").trim();
}

function failureLabel(sample: SampleScore): string {
  const dimensions = new Set(
    sample.features.flatMap((feature) =>
      feature.dimensions
        .filter((dimension) => dimension.score <= 2)
        .map((dimension) => dimension.dimension),
    ),
  );

  const labels: string[] = [];
  if (dimensions.has("technique")) labels.push("technique not named and justified");
  if (dimensions.has("emotion")) labels.push("tone misses the scene");
  if (dimensions.has("consistency")) labels.push("contradicts the story bible");

  return labels.length > 0 ? labels.join("; ") : "overall score below 3";
}

function renderFailure(
  sample: SampleScore,
  index: number,
  provider: string,
): string[] {
  const lines = [
    `### ${index + 1}. ${sample.title} (\`${sample.id}\`) — ${failureLabel(sample)}`,
    "",
    `- **${provider === "stub" ? "Stub flavor" : "Sample tag"}:** \`${sample.stubFlavor}\``,
    `- **Overall:** ${sample.overall.toFixed(1)}/5`,
    `- **Why it failed:** ${sample.reasons.join("; ")}`,
  ];

  for (const feature of sample.features) {
    for (const dimension of feature.dimensions) {
      if (dimension.score > 2) continue;
      lines.push(
        `- **${feature.feature} / ${dimension.dimension} — ${dimension.score}/5:** ${dimension.rationale}`,
      );
      for (const evidence of dimension.evidence) {
        lines.push(`  - ${evidence}`);
      }
    }
  }

  lines.push("");
  return lines;
}

export function renderReport(run: EvalRun): string {
  const failures = run.samples.filter((sample) => sample.failed);
  const shownFailures = failures.slice(0, 3);

  const lines: string[] = [
    "# AI Screenplay Studio eval results",
    "",
    `- **Provider:** \`${run.provider}\`${
      run.model ? ` (model \`${run.model}\`)` : ""
    }`,
    `- **Samples:** ${run.samples.length}`,
    `- **Features:** \`nextLines\`, \`shotList\` (two scored outputs per sample)`,
    `- **Failure cases:** ${failures.length}`,
    "",
    "> Generated by `npm run eval`. The default run is deterministic and makes",
    "> no network calls; use `npm run eval -- --provider=live` for a real model.",
    "",
    "## Rubric",
    "",
    "Each feature is scored from 1 (missed) to 5 (strong) on three dimensions:",
    "",
    "1. **Technique named and justified** — the response names a specific craft",
    "   technique and explains why it serves this scene.",
    "2. **Matches scene emotion** — the word choice, shots, and direction fit the",
    "   scene's emotional register instead of fighting it.",
    "3. **Consistent with the story bible** — the response uses established story",
    "   anchors and avoids contradictions.",
    "",
    "A sample fails if any dimension scores 2 or lower, or if its overall score is",
    "below 3. The report shows up to three failure cases in detail.",
    "",
    "## Summary",
    "",
    "`T/E/C` means technique / emotion / consistency.",
    "",
    "| # | Sample | nextLines (T/E/C) | shotList (T/E/C) | Overall | Result |",
    "| ---: | --- | :---: | :---: | ---: | :--- |",
  ];

  run.samples.forEach((sample, index) => {
    const nextLines = sample.features.find(
      (feature) => feature.feature === "nextLines",
    );
    const shotList = sample.features.find(
      (feature) => feature.feature === "shotList",
    );

    lines.push(
      `| ${index + 1} | ${escapeCell(sample.title)} (\`${sample.id}\`) | ${
        nextLines ? formatFeature(nextLines) : "—"
      } | ${shotList ? formatFeature(shotList) : "—"} | ${sample.overall.toFixed(
        1,
      )} | ${sample.failed ? "**fail**" : "pass"} |`,
    );
  });

  lines.push("", "## Failure cases", "");

  if (shownFailures.length === 0) {
    lines.push(
      "No samples failed in this run. The deterministic stub run keeps three",
      "known-bad samples so the rubric's failure paths stay visible in CI.",
      "",
    );
  } else {
    shownFailures.forEach((sample, index) => {
      lines.push(...renderFailure(sample, index, run.provider));
    });

    if (failures.length > shownFailures.length) {
      lines.push(
        `_${failures.length - shownFailures.length} additional failing sample${
          failures.length - shownFailures.length === 1 ? " is" : "s are"
        } listed in the summary table._`,
        "",
      );
    }
  }

  lines.push(
    "## What this does not measure",
    "",
    "These are deterministic keyword and structure heuristics, not an LLM judge.",
    "They catch missing technique, tonal drift, and bible contradictions, but they",
    "do not measure originality, producibility, or whether a line is actually",
    "funny. Treat the live run as a smoke test and read the outputs yourself.",
    "",
  );

  return lines.join("\n");
}
